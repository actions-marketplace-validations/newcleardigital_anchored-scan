#!/usr/bin/env python3
"""Anchored Scan: the Anchored Lite checks as a GitHub Action.

Two modes, chosen by the repository itself:

* No anchor-core.json (zero-config). Looks for two things any codebase has and
  nobody notices until they bite: a fixed number used in logic in more than one
  file (the next change will miss a copy), and a generated file edited by hand
  in this pull request. Advisory: never fails the build unless asked to.
* anchor-core.json present. Runs the four Lite checks exactly as the plugin and
  run.sh do (same code, vendored in gates/), and fails the build when one fails.

Writes a Markdown report to stdout, to $GITHUB_STEP_SUMMARY, and as one pull
request comment that is updated in place. Standard library only.
"""
import argparse, json, os, pathlib, re, subprocess, sys, urllib.request, urllib.error

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE / "gates"))
import _core as C  # noqa: E402

MARKER = "<!-- anchored-scan -->"
SITE = "https://anchored.newcleardigital.com/"
LITE = "https://github.com/newcleardigital/anchored-lite"
SCAN = "https://github.com/newcleardigital/anchored-scan"
# Numbers that are almost always units, sizes, bit masks, status codes or loop
# bounds, not product decisions. Small whole numbers are left out on purpose:
# in an unknown codebase they are mostly indexes and counts.
TRIVIAL = {0.5, 0.25, 0.1, 0.01, 24, 30, 60, 90, 100, 180, 360, 365, 1000, 3600, 86400, 10000, 100000, 1000000}
HTTP = {200, 201, 202, 204, 301, 302, 303, 304, 307, 308, 400, 401, 403, 404, 405, 409, 410, 412, 413,
        415, 422, 429, 500, 501, 502, 503, 504}
THIRD_PARTY = {"_vendor", "vendor", "vendored", "third_party", "thirdparty", "external", "deps", "migrations",
               "node_modules", "dist", "build", "generated", "__generated__", ".yarn", "mocks", "__mocks__",
               "stories", "storybook-static", "coverage"}
MAX_BYTES = 400_000  # bundles and minified files are not anyone's source


def trivial(v):
    if v in TRIVIAL or v in HTTP:
        return True
    if v == int(v):
        n = int(v)
        if n < 20:
            return True
        if n & (n - 1) == 0 or (n + 1) & n == 0:  # 2^k and 2^k - 1: sizes and masks
            return True
    return False


def weight(v):
    """Rates and odd amounts are far more likely to be product decisions."""
    if v != int(v):
        return 0
    return 1 if v >= 1000 else 2
GENERATED_HEAD = re.compile(r"do not edit|@generated|auto-?generated|generated by|this file is generated", re.I)
CHECKS = [("generated files in sync", "check_generated.py", 3),
          ("fixed numbers in one place", "check_numbers.py", 1),
          ("agreed vocabulary", "check_words.py", 2),
          ("decisions written down", "check_decisions.py", 4)]


# ---------------------------------------------------------------- findings

def zero_config(root):
    cfg = dict(C.DEFAULTS)
    cfg.update(root=root, languages=C.detect_languages(root))
    return cfg


def copied_values(cfg):
    """value -> list of (rel, line) where it is used in logic, outside tests."""
    comment = C.profile(cfg)["line_comment"]
    uses = {}
    for p in C.sources(cfg):
        rel = p.relative_to(cfg["root"])
        if C.is_test(rel) or THIRD_PARTY & {x.lower() for x in rel.parts}:
            continue
        if p.stat().st_size > MAX_BYTES or p.name.endswith((".min.js", ".bundle.js")):
            continue
        lines = p.read_text(errors="replace").splitlines()
        for i, line in enumerate(lines):
            if C.escaped(cfg, lines, i):
                continue
            code = C.strip_code(line, comment)
            for rx, _how in C.number_patterns():
                for m in rx.finditer(code):
                    v = float(m.group(1))
                    if trivial(v):
                        continue
                    uses.setdefault(v, set()).add((str(rel), i + 1))
    out = []
    for v, where in uses.items():
        files = {f for f, _ in where}
        if len(files) >= 2:
            out.append((v, sorted(where)))
    out.sort(key=lambda kv: (weight(kv[0]), -len({f for f, _ in kv[1]}), kv[0]))
    return out


def generated_edits(root, changed, cfg_generated):
    named = {g["file"] for g in cfg_generated if isinstance(g, dict) and g.get("file")}
    hits = []
    for rel in changed:
        p = root / rel
        if not p.is_file():
            continue
        if rel in named:
            hits.append((rel, "listed as generated in anchor-core.json"))
            continue
        try:
            head = "\n".join(p.read_text(errors="replace").splitlines()[:6])
        except OSError:
            continue
        if GENERATED_HEAD.search(head):
            hits.append((rel, "its header says it is generated"))
    return hits


def run_checks(root):
    env = dict(os.environ, CLAUDE_PROJECT_DIR=str(root))
    results = []
    for title, script, problem in CHECKS:
        r = subprocess.run([sys.executable, str(HERE / "gates" / script)], cwd=root, env=env,
                           capture_output=True, text=True, timeout=600)
        lines = [ln for ln in (r.stdout + r.stderr).splitlines() if ln.strip()]
        results.append((title, r.returncode == 0, lines, problem))
    return results


# ---------------------------------------------------------------- GitHub

def event():
    p = os.environ.get("GITHUB_EVENT_PATH")
    if p and os.path.isfile(p):
        with open(p) as f:
            return json.load(f)
    return {}


def api(method, url, token, body=None):
    req = urllib.request.Request(url, method=method, data=json.dumps(body).encode() if body else None,
                                 headers={"Authorization": f"Bearer {token}",
                                          "Accept": "application/vnd.github+json",
                                          "User-Agent": "anchored-scan"})
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.loads(r.read() or b"null")


def pr_files(token, repo, number):
    base = os.environ.get("GITHUB_API_URL", "https://api.github.com")
    files, page = [], 1
    while page <= 30:
        batch = api("GET", f"{base}/repos/{repo}/pulls/{number}/files?per_page=100&page={page}", token)
        files += [f["filename"] for f in batch if f.get("status") != "removed"]
        if len(batch) < 100:
            break
        page += 1
    return files


def upsert_comment(token, repo, number, body):
    base = os.environ.get("GITHUB_API_URL", "https://api.github.com")
    page = 1
    while page <= 20:
        batch = api("GET", f"{base}/repos/{repo}/issues/{number}/comments?per_page=100&page={page}", token)
        for c in batch:
            if MARKER in (c.get("body") or ""):
                api("PATCH", c["url"], token, {"body": body})
                return "updated"
        if len(batch) < 100:
            break
        page += 1
    api("POST", f"{base}/repos/{repo}/issues/{number}/comments", token, {"body": body})
    return "created"


# ---------------------------------------------------------------- report

def fmt(v):
    return str(int(v)) if v == int(v) else repr(v)


def report(mode, copies, edits, checks, changed, repo):
    changed = set(changed or [])
    out = [MARKER, "### Anchored Scan", ""]
    if mode == "checks":
        failed = [c for c in checks if not c[1]]
        if failed:
            out.append(f"**{len(failed)} of {len(checks)} checks failed** · rules from `anchor-core.json`")
        else:
            out.append(f"**All {len(checks)} checks green** · rules from `anchor-core.json`")
        out.append("")
        out.append("| Check | Result |")
        out.append("|---|---|")
        for title, good, _lines, _p in checks:
            out.append(f"| {title} | {'✅ green' if good else '❌ failed'} |")
        for title, good, lines, _p in checks:
            if not good:
                out += ["", f"<details open><summary><b>{title}</b></summary>", "", "```"]
                out += lines[:30] + (["…"] if len(lines) > 30 else [])
                out += ["```", "</details>"]
    else:
        parts = []
        parts.append(f"{len(copies)} possible copied fixed value{'s' if len(copies) != 1 else ''}")
        if changed:
            parts.append(f"{len(edits)} generated file{'s' if len(edits) != 1 else ''} edited in this PR")
        out.append("**" + " · ".join(parts) + "** · zero-config, advisory")
    if copies:
        out += ["", "#### Fixed numbers used in logic in more than one file",
                "When this value changes, one copy will be missed. Keep it in one constants file and read it from there.",
                "", "| Value | Files | Where |", "|---|---|---|"]
        for v, where in copies[:12]:
            files = {f for f, _ in where}
            locs = [f"`{f}:{ln}`" + (" ✱" if f in changed else "") for f, ln in where[:3]]
            more = f" +{len(where) - 3}" if len(where) > 3 else ""
            out.append(f"| `{fmt(v)}` | {len(files)} | {', '.join(locs)}{more} |")
        if len(copies) > 12:
            out.append(f"| … | | {len(copies) - 12} more |")
        if changed and any(f in changed for _, w in copies for f, _ in w):
            out.append("")
            out.append("✱ file changed in this pull request")
    if edits:
        out += ["", "#### Generated files edited in this pull request",
                "A hand edit is lost the next time the generator runs, and until then the file no longer says what its source says.",
                ""]
        out += [f"- `{rel}` — {why}" for rel, why in edits]
    if mode == "zero" and not copies and not edits:
        out += ["", "Nothing found. No fixed number is used in logic in two files" +
                (", and no generated file was edited here." if changed else ".")]
    if mode == "zero":
        out += ["", "<details><summary>Make these enforced rules</summary>", "",
                "Add an `anchor-core.json` at the repository root naming the numbers your product decides on purpose, "
                "the one file they live in, the words the team agreed not to use and the files that are generated. "
                "The scan then fails the build on a break instead of advising.",
                "", f"With [Anchored Lite]({LITE}) for Claude Code the agent is stopped the moment it writes the copy, "
                "and fixes it in the same turn.", "", "</details>"]
    badge = f"[![checked by Anchored](https://img.shields.io/badge/checked%20by-Anchored-2F5E8C)]({SITE}?ref=badge)"
    out += ["", "---",
            f"<sub>Free scan by [Anchored Scan]({SCAN}). Show it in your README: <code>{badge}</code>. "
            f"If this code follows an outside rulebook — card-scheme rules, regulator fees, a contract — "
            f"[Anchored]({SITE}?ref=scan-comment) traces each rule to its code, test and named approver.</sub>"]
    return "\n".join(out) + "\n"


# ---------------------------------------------------------------- main

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--path", default=".")
    ap.add_argument("--fail-on", default="auto", choices=["auto", "never", "findings"])
    ap.add_argument("--comment", default="true")
    ap.add_argument("--changed", default="", help="comma-separated paths (testing without GitHub)")
    a = ap.parse_args()

    root = pathlib.Path(a.path).resolve()
    token = os.environ.get("INPUT_TOKEN") or os.environ.get("GITHUB_TOKEN") or ""
    repo = os.environ.get("GITHUB_REPOSITORY", "")
    ev = event()
    number = (ev.get("pull_request") or {}).get("number")

    changed = [x for x in a.changed.split(",") if x]
    if not changed and number and token and repo:
        try:
            changed = pr_files(token, repo, number)
        except (urllib.error.URLError, OSError) as e:
            print(f"::warning::Anchored Scan could not list the pull request's files: {e}", file=sys.stderr)

    # The pull request lists paths from the repository root; the scan works relative to --path.
    workspace = pathlib.Path(os.environ.get("GITHUB_WORKSPACE") or os.getcwd()).resolve()
    try:
        prefix = root.relative_to(workspace).as_posix()
    except ValueError:
        prefix = "."
    if prefix != "." and not a.changed:
        changed = [c[len(prefix) + 1:] for c in changed if c.startswith(prefix + "/")]

    configured = (root / C.CONFIG_NAME).is_file()
    if configured:
        cfg = C.load(root)
        checks = run_checks(root)
        copies = []
        edits = [e for e in generated_edits(root, changed, cfg["generated"])
                 if e[1] != "listed as generated in anchor-core.json"]  # check_generated owns those
        mode = "checks"
    else:
        cfg = zero_config(root)
        checks = []
        copies = copied_values(cfg)
        edits = generated_edits(root, changed, [])
        mode = "zero"

    body = report(mode, copies, edits, checks, changed, repo)
    print(body)
    summary = os.environ.get("GITHUB_STEP_SUMMARY")
    if summary:
        with open(summary, "a") as f:
            f.write(body.replace(MARKER + "\n", ""))

    if a.comment.lower() == "true" and number and token and repo:
        try:
            print(f"Pull request comment {upsert_comment(token, repo, number, body)}.")
        except urllib.error.HTTPError as e:
            # Pull requests from forks get a read-only token. The step summary still has the report.
            print(f"::notice::Anchored Scan could not comment (HTTP {e.code}); the report is in the job summary.")
        except (urllib.error.URLError, OSError) as e:
            print(f"::notice::Anchored Scan could not comment ({e}); the report is in the job summary.")

    failed = any(not c[1] for c in checks)
    out = os.environ.get("GITHUB_OUTPUT")
    if out:
        with open(out, "a") as f:
            f.write(f"mode={mode}\ncopies={len(copies)}\ngenerated-edits={len(edits)}\nfailed={str(failed).lower()}\n")

    if a.fail_on == "never":
        return 0
    if a.fail_on == "findings":
        return 1 if (failed or copies or edits) else 0
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
